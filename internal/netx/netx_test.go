package netx

import (
	"net"
	"testing"
)

func TestIsBlocked(t *testing.T) {
	own := []net.IP{net.ParseIP("203.0.113.10")}
	blocked := []string{
		"127.0.0.1",
		"10.1.2.3",
		"192.168.1.1",
		"172.16.0.1",
		"172.31.255.1",
		"169.254.169.254",
		"203.0.113.10",
		"::ffff:203.0.113.10",
		"::1",
		"fe80::1",
		"fc00::1",
		"0.0.0.0",
		"0.1.2.3",
		"100.64.0.1",
		"100.127.255.254",
		"192.0.0.8",
		"198.18.0.1",
		"240.0.0.1",
		"255.255.255.255",
		"224.0.0.1",
		"::ffff:127.0.0.1",
		"64:ff9b::7f00:1",  // NAT64 of 127.0.0.1
		"64:ff9b::a00:1",   // NAT64 of 10.0.0.1
		"2002:7f00:1::1",   // 6to4 of 127.0.0.1
		"2002:c0a8:101::1", // 6to4 of 192.168.1.1
		"2001::1",
	}
	for _, s := range blocked {
		if !IsBlocked(net.ParseIP(s), own) {
			t.Errorf("ждали блок %s", s)
		}
	}
	open := []string{
		"203.0.113.11",
		"8.8.8.8",
		"172.15.5.5",
		"100.128.0.1",
		"2606:4700::1111",
		"64:ff9b::808:808", // NAT64 of 8.8.8.8
	}
	for _, s := range open {
		if IsBlocked(net.ParseIP(s), own) {
			t.Errorf("ждали открыт %s", s)
		}
	}
	if !IsBlocked(nil, nil) {
		t.Error("nil не заблокирован")
	}
}
